def page_today(st, conn, uid):
    st.subheader("Today's Prayers")
    day = st.date_input("Date", value=date.today(), max_value=date.today())
    statuses = get_day_statuses(conn, uid, day)

    for prayer in PRAYERS:
        current = STATUS_LABELS[statuses.get(prayer)]
        options = list(STATUS_LABELS.values())
        choice = st.radio(
            prayer, options, index=options.index(current), horizontal=True,
            key=f"radio_{prayer}_{day.isoformat()}",
        )
        if choice != current:
            new_status = LABEL_TO_STATUS[choice]
            if new_status is None:
                clear_status(conn, uid, day, prayer)
            else:
                set_status(conn, uid, day, prayer, new_status)
            st.rerun()

    completed, total, percent = daily_progress(statuses)
    st.progress(completed / total, text=f"{completed} of {total} prayers completed ({percent:.0f}%)")
    st.info(POSITIVE_MESSAGES[completed])
    streak = current_streak(conn, uid, date.today())
    st.metric("Current streak (all five prayers)", f"{streak} day(s)")
    st.markdown("##### Daily Reminder")
    render_source_card(st, daily_reminder(day))


