def page_missed(st, conn, uid):
    st.subheader("Missed Prayers (Private)")
    st.info(MISSED_ENCOURAGEMENT)

    with st.form("missed_form", clear_on_submit=True):
        day = st.date_input("Date of missed prayer", value=date.today(), max_value=date.today())
        prayer = st.selectbox("Prayer", PRAYERS)
        note = st.text_input("Private note (optional)", max_chars=MAX_NOTE_LENGTH)
        if st.form_submit_button("Save record"):
            try:
                set_status(conn, uid, day, prayer, STATUS_MISSED, note)
                st.success("Saved. May Allah make it easy for you.")
            except ValueError as err:
                st.error(str(err))

    missed = get_missed(conn, uid)
    if not missed:
        st.success("No missed prayers recorded. Alhamdulillah!")
        return
    st.markdown("##### Prayers to make up")
    for i, item in enumerate(missed):
        left, right = st.columns([3, 2])
        left.write(f"**{item['prayer']}** - {item['log_date']}" + (f"  \n_{item['note']}_" if item["note"] else ""))
        if right.button("Mark as made up", key=f"makeup_{i}"):
            set_status(conn, uid, date.fromisoformat(item["log_date"]), item["prayer"],
                       STATUS_MADE_UP, item["note"])
            st.rerun()


