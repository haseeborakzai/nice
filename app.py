# 5. PROGRESS AND REPORTS (Pandas)
# ---------------------------------------------------------------------------
def daily_progress(statuses):
    """Return (completed, total, percent) from a {prayer: status} dictionary."""
    completed = sum(1 for s in statuses.values() if s in COMPLETED_STATUSES)
    total = len(PRAYERS)
    return completed, total, round(completed / total * 100, 1)


def _log_dataframe(conn, user_id, start, end):
    rows = conn.execute(
        "SELECT log_date, prayer, status FROM prayer_log "
        "WHERE user_id = ? AND log_date BETWEEN ? AND ?",
        (user_id, start.isoformat(), end.isoformat()),
    ).fetchall()
    return pd.DataFrame(
        [dict(r) for r in rows], columns=["log_date", "prayer", "status"]
    )


def history_report(conn, user_id, start, end):
    """One row per day: completed count, missed count and completion percent."""
    if start > end:
        raise ValueError("Start date must not be after end date.")
    log = _log_dataframe(conn, user_id, start, end)
    days = pd.date_range(start, end).date
    report = pd.DataFrame({"date": days})
    report["completed"] = report["date"].map(
        lambda d: int(
            ((log["log_date"] == d.isoformat()) & log["status"].isin(COMPLETED_STATUSES)).sum()
        )
    )
    report["missed"] = report["date"].map(
        lambda d: int(
            ((log["log_date"] == d.isoformat()) & (log["status"] == STATUS_MISSED)).sum()
        )
    )
    report["percent"] = (report["completed"] / len(PRAYERS) * 100).round(1)
    return report


def per_prayer_report(conn, user_id, start, end):
    """For each of the five prayers: days completed and completion rate."""
    log = _log_dataframe(conn, user_id, start, end)
    num_days = (end - start).days + 1
    rows = []
    for prayer in PRAYERS:
        done = int(((log["prayer"] == prayer) & log["status"].isin(COMPLETED_STATUSES)).sum())
        rows.append(
            {"prayer": prayer, "completed": done, "rate": round(done / num_days * 100, 1)}
        )
    return pd.DataFrame(rows)


def current_streak(conn, user_id, today):
    """Consecutive days (ending today, or yesterday) with all five prayers done."""
    report = history_report(conn, user_id, today - timedelta(days=365), today)
    full = dict(zip(report["date"], report["completed"] == len(PRAYERS)))
    day = today if full.get(today) else today - timedelta(days=1)
    streak = 0
    while full.get(day):
        streak += 1
        day -= timedelta(days=1)
    return streak


