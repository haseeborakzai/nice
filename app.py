def get_connection(path=None):
    conn = sqlite3.connect(path or DB_PATH, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_db(conn):
    conn.executescript(
        """
        CREATE TABLE IF NOT EXISTS users (
            id        INTEGER PRIMARY KEY AUTOINCREMENT,
            username  TEXT NOT NULL UNIQUE,
            salt      BLOB NOT NULL,
            pin_hash  BLOB NOT NULL
        );
        CREATE TABLE IF NOT EXISTS prayer_log (
            user_id   INTEGER NOT NULL,
            log_date  TEXT NOT NULL,
            prayer    TEXT NOT NULL,
            status    TEXT NOT NULL,
            note      TEXT NOT NULL DEFAULT '',
            PRIMARY KEY (user_id, log_date, prayer),
            FOREIGN KEY (user_id) REFERENCES users(id)
        );
        """
    )
    conn.commit()


def _hash_pin(pin, salt):
    return hashlib.pbkdf2_hmac("sha256", pin.encode("utf-8"), salt, PIN_ITERATIONS)


def create_user(conn, username, pin):
    """Create a profile. The PIN is never stored, only a salted hash."""
    username = validate_username(username)
    pin = validate_pin(pin)
    salt = secrets.token_bytes(16)
    try:
        cur = conn.execute(
            "INSERT INTO users (username, salt, pin_hash) VALUES (?, ?, ?)",
            (username, salt, _hash_pin(pin, salt)),
        )
        conn.commit()
    except sqlite3.IntegrityError:
        raise ValueError("That username is already taken.")
    return cur.lastrowid


def authenticate(conn, username, pin):
    """Return the user id if username and PIN match, otherwise None."""
    try:
        username = validate_username(username)
        pin = validate_pin(pin)
    except ValueError:
        return None
    row = conn.execute(
        "SELECT id, salt, pin_hash FROM users WHERE username = ?", (username,)
    ).fetchone()
    if row is None:
        return None
    if hmac.compare_digest(_hash_pin(pin, row["salt"]), row["pin_hash"]):
        return row["id"]
    return None


def set_status(conn, user_id, day, prayer, status, note=""):
    """Insert or update one prayer record (parameterised SQL prevents injection)."""
    validate_date(day)
    validate_prayer(prayer)
    validate_status(status)
    note = validate_note(note)
    conn.execute(
        """
        INSERT INTO prayer_log (user_id, log_date, prayer, status, note)
        VALUES (?, ?, ?, ?, ?)
        ON CONFLICT(user_id, log_date, prayer)
        DO UPDATE SET status = excluded.status, note = excluded.note
        """,
        (user_id, day.isoformat(), prayer, status, note),
    )
    conn.commit()


def clear_status(conn, user_id, day, prayer):
    validate_prayer(prayer)
    conn.execute(
        "DELETE FROM prayer_log WHERE user_id = ? AND log_date = ? AND prayer = ?",
        (user_id, day.isoformat(), prayer),
    )
    conn.commit()


def get_day_statuses(conn, user_id, day):
    """Return {prayer: status} for one day (only prayers that were recorded)."""
    rows = conn.execute(
        "SELECT prayer, status FROM prayer_log WHERE user_id = ? AND log_date = ?",
        (user_id, day.isoformat()),
    ).fetchall()
    return {r["prayer"]: r["status"] for r in rows}


def get_missed(conn, user_id):
    """All prayers currently marked as missed, newest first."""
    rows = conn.execute(
        "SELECT log_date, prayer, note FROM prayer_log "
        "WHERE user_id = ? AND status = ? ORDER BY log_date DESC",
        (user_id, STATUS_MISSED),
    ).fetchall()
    return [dict(r) for r in rows]


def delete_all_user_data(conn, user_id):
    """Let a user erase their whole account and history."""
    conn.execute("DELETE FROM prayer_log WHERE user_id = ?", (user_id,))
    conn.execute("DELETE FROM users WHERE id = ?", (user_id,))
    conn.commit()


