class AIServiceError(Exception):
    """Raised with a user-friendly message when the AI call cannot be completed."""


def get_api_key(secrets_source=None):
    """Read the key from Streamlit secrets or the environment. Never hard-coded."""
    if secrets_source is not None:
        try:
            key = secrets_source.get("GEMINI_API_KEY")
            if key:
                return key
        except Exception:
            pass
    return os.environ.get("GEMINI_API_KEY")


def ask_gemini(question, api_key=None, client=None, model=None):
    """
    Ask Gemini a question. Pass `client` to use a fake client in tests.
    Returns the answer text or raises AIServiceError with a friendly message.
    """
    question = validate_question(question)
    model = model or os.environ.get("GEMINI_MODEL") or DEFAULT_MODEL

    if client is None:
        if not api_key:
            raise AIServiceError(
                "The AI assistant is not configured. Add GEMINI_API_KEY to the app secrets."
            )
        try:
            from google import genai  # imported here so tests do not need the SDK

            client = genai.Client(api_key=api_key)
        except Exception:
            raise AIServiceError("Could not start the AI service. Please try again later.")

    try:
        try:
            from google.genai import types

            config = types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT, temperature=0.3, max_output_tokens=700
            )
        except ImportError:  # SDK missing (only happens in tests with a fake client)
            config = {"system_instruction": SYSTEM_PROMPT}
        response = client.models.generate_content(
            model=model, contents=question, config=config
        )
        text = (getattr(response, "text", "") or "").strip()
    except Exception:
        raise AIServiceError(
            "The AI service is not available right now (network, quota or key problem). "
            "Please try again later."
        )
    if not text:
        raise AIServiceError("The AI returned an empty answer. Please rephrase your question.")
    return text


