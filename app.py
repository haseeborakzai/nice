def validate_username(username):
    username = (username or "").strip()
    if not re.fullmatch(r"[A-Za-z0-9_]{3,20}", username):
        raise ValueError("Username must be 3-20 characters: letters, numbers or underscore.")
    return username.lower()


def validate_pin(pin):
    pin = (pin or "").strip()
    if not re.fullmatch(r"\d{4,8}", pin):
        raise ValueError("PIN must be 4-8 digits.")
    return pin


def validate_prayer(prayer):
    if prayer not in PRAYERS:
        raise ValueError(f"Unknown prayer: {prayer!r}")
    return prayer


def validate_status(status):
    if status not in VALID_STATUSES:
        raise ValueError(f"Unknown status: {status!r}")
    return status


def validate_date(value):
    if not isinstance(value, date):
        raise ValueError("Invalid date.")
    if value > date.today() + timedelta(days=1):  # +1 day tolerates time zones
        raise ValueError("Future dates are not allowed.")
    return value


def validate_note(note):
    note = (note or "").strip()
    if len(note) > MAX_NOTE_LENGTH:
        raise ValueError(f"Note must be at most {MAX_NOTE_LENGTH} characters.")
    return note


def validate_question(question):
    question = (question or "").strip()
    if len(question) < 3:
        raise ValueError("Please type a question (at least 3 characters).")
    if len(question) > MAX_QUESTION_LENGTH:
        raise ValueError(f"Question must be at most {MAX_QUESTION_LENGTH} characters.")
    return question


